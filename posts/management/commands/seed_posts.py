class Command(BaseCommand):
    help = "پست‌های اولیه‌ی مجله را در دیتابیس می‌سازد یا به‌روزرسانی می‌کند."

    def handle(self, *args, **options):
        created, updated = 0, 0
        for item in SEED:
            payload = {k: v for k, v in item.items() if k != "slug" and k != "content"}
            payload["content"] = "\n\n".join(item["content"])
            obj, was_created = Post.objects.update_or_create(slug=item["slug"], defaults=payload)
            created += int(was_created)
            updated += int(not was_created)
        self.stdout.write(self.style.SUCCESS(f"{created} posts created, {updated} posts updated."))
